"""Generates TASKS.md, a checklist view of ROADMAP.md.

ROADMAP.md is the source of truth (tables with a description for every item).
Run `python3 scripts/tasks.py` after changing it; `--check` fails when TASKS.md is out of date.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROADMAP = ROOT / "ROADMAP.md"
TASKS = ROOT / "TASKS.md"

VERSION = re.compile(r"(?:Done in |Done: |\(|since |in )(addon|server) (\d+\.\d+\.\d+)")


def shipped_in(text):
    """First addon and server version mentioned in a done item, e.g. 'addon 0.6.0, server 0.7.0'."""
    found = {}
    for kind, version in VERSION.findall(text):
        found.setdefault(kind, version)
    return ", ".join(f"{kind} {found[kind]}" for kind in ("addon", "server") if kind in found)


def parse(lines):
    """Yields (section title, [items]) for the numbered sections of the roadmap."""
    title, items = None, []
    for line in lines:
        heading = re.match(r"^## (\d+\. .+)$", line)
        if heading:
            if title:
                yield title, items
            title, items = heading.group(1), []
            continue
        if line.startswith("## ") and title:
            yield title, items
            title, items = None, []
            continue
        row = re.match(r"^\| (\d+) \| (.+)\|\s*$", line)
        if title and row:
            cells = [cell.strip() for cell in row.group(2).split(" | ")]
            name = cells[0]
            rest = " ".join(cells[1:])
            done = name.startswith("✅")
            partly = name.startswith("◐")
            declined = name.lower().startswith("checked, deliberately not doing")
            name = re.sub(r"\s*\(partly\)$", "", name.lstrip("✅◐ ").strip())
            items.append({
                "id": int(row.group(1)), "name": name, "done": done, "partly": partly,
                "declined": declined, "version": shipped_in(rest) if done else "",
            })
    if title:
        yield title, items


def render(sections):
    sections = list(sections)
    everything = [item for _, items in sections for item in items]
    done = sum(1 for item in everything if item["done"])
    out = [
        "# wow-mcp tasks",
        "",
        "A checklist view of [ROADMAP.md](ROADMAP.md), generated by `python3 scripts/tasks.py`. Do not edit by hand:",
        "change the roadmap and regenerate. Details of every item are in the roadmap; what shipped in which version is in",
        "[CHANGELOG.md](CHANGELOG.md).",
        "",
        f"**Progress: {done} of {len(everything)} done.** `[x]` done · `[ ]` open · *(partly)* started, not finished ·",
        "*(declined)* checked and deliberately not done.",
        "",
    ]
    for title, items in sections:
        section_done = sum(1 for item in items if item["done"])
        out += [f"## {title} ({section_done}/{len(items)})", ""]
        for item in items:
            box = "x" if item["done"] else " "
            note = ""
            if item["version"]:
                note = f" — {item['version']}"
            elif item["partly"]:
                note = " *(partly)*"
            elif item["declined"]:
                note = " *(declined)*"
            out.append(f"- [{box}] **{item['id']}.** {item['name']}{note}")
        out.append("")
    open_items = [item for item in everything if not item["done"] and not item["declined"]]
    out += ["## Still open", ""]
    out += [f"- [ ] **{item['id']}.** {item['name']}" + (" *(partly)*" if item["partly"] else "") for item in open_items]
    out.append("")
    return "\n".join(out)


def main():
    text = render(parse(ROADMAP.read_text(encoding="utf-8").splitlines()))
    if "--check" in sys.argv:
        if not TASKS.exists() or TASKS.read_text(encoding="utf-8") != text:
            sys.exit("TASKS.md is out of date: run python3 scripts/tasks.py")
        return
    TASKS.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
