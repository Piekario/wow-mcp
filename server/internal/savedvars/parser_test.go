func TestParseLiterals(t *testing.T) {
	src := `
-- komentarz na gorze
Sample = {
	["text"] = "a \"quoted\" \\ back\nline",
	["int"] = 42,
	["neg"] = -7,
	["float"] = 43.5,
	["exp"] = 1e3,
	["yes"] = true,
	["no"] = false,
	["nothing"] = nil,
	["list"] = {
		"a", -- [1]
		"b", -- [2]
	},
	["empty"] = {
	},
	["sparse"] = {
		[2] = "two",
		[5] = "five",
	},
	bare = 'single',
	["bytes"] = "Zo\195\171 \195\133ngstr\195\182m",
}
Other = "x"
`
	vars, err := Parse([]byte(src))
	if err != nil {
		t.Fatal(err)
	}
	want := map[string]any{
		"text":    "a \"quoted\" \\ back\nline",
		"int":     int64(42),
		"neg":     int64(-7),
		"float":   43.5,
		"exp":     1000.0,
		"yes":     true,
		"no":      false,
		"nothing": nil,
		"list":    []any{"a", "b"},
		"empty":   []any{},
		"sparse":  map[string]any{"2": "two", "5": "five"},
		"bare":    "single",
		"bytes":   "Zoë Ångström",
	}
	if !reflect.DeepEqual(vars["Sample"], want) {
		t.Errorf("Sample:\n got %#v\nwant %#v", vars["Sample"], want)
	}
	if vars["Other"] != "x" {
		t.Errorf("Other = %#v", vars["Other"])
	}
}

func TestParseErrors(t *testing.T) {
	for _, src := range []string{
		`X = {`,
		`X = "abc`,
		`X = { ["a"] "b" }`,
		`= 1`,
		`X = unknownword`,
	} {
		if _, err := Parse([]byte(src)); err == nil {
			t.Errorf("no error for %q", src)
		}
	}
}

// A file generated by the real addon code run with game API stubs.
func TestParseAddonOutput(t *testing.T) {
	for _, name := range []string{"../../testdata/WowMcp.lua", "../../testdata/WowMcp_legacy.lua", "../../testdata/WowMcp_forever.lua"} {
		src, err := os.ReadFile(name)
		if err != nil {
			t.Fatal(err)
		}
		vars, err := Parse(src)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		db, ok := vars["WowMcpDB"].(map[string]any)
		if !ok {
			t.Fatalf("%s: no WowMcpDB", name)
		}
		if db["last"] != "Piekasz" {
			t.Errorf("%s: last = %#v", name, db["last"])
		}
		snapshot := db["characters"].(map[string]any)["Piekasz"].(map[string]any)
		character := snapshot["character"].(map[string]any)
		if character["level"] != int64(20) || character["class"] != "Hunter" {
			t.Errorf("%s: character = %#v", name, character)
		}
		quests := snapshot["quests"].([]any)
		first := quests[0].(map[string]any)
		if first["title"] != "Cave Mushrooms" {
			t.Errorf("%s: first quest = %#v", name, first)
		}
		objectives := first["objectives"].([]any)
		if len(objectives) != 2 || objectives[1].(map[string]any)["done"] != false {
			t.Errorf("%s: objectives = %#v", name, objectives)
		}
	}
}

// Fuzzing regression: deeply nested tables overflowed the stack (a fatal error).
func TestParseRejectsDeepNesting(t *testing.T) {
	for name, src := range map[string]string{
		"tables":          "X = " + strings.Repeat("{", 3_000_000),
		"keys":            "X = " + strings.Repeat("{[", 1_000_000),
		"just over limit": "X = " + strings.Repeat("{", maxDepth+1) + strings.Repeat("}", maxDepth+1),
	} {
		_, err := Parse([]byte(src))
		if err == nil || !strings.Contains(err.Error(), "nested") {
			t.Errorf("%s: expected a nesting error, got %v", name, err)
		}
	}
	ok := "X = " + strings.Repeat("{", maxDepth) + strings.Repeat("}", maxDepth)
	if _, err := Parse([]byte(ok)); err != nil {
		t.Errorf("nesting equal to the limit should pass: %v", err)
	}
}

// Regression: every block comment copied the rest of the file (quadratic time).
func TestParseManyBlockCommentsIsFast(t *testing.T) {
	src := "X = 1 " + strings.Repeat("--[[a]]", 200_000)
	start := time.Now()
	if _, err := Parse([]byte(src)); err != nil {
		t.Fatal(err)
	}
	if d := time.Since(start); d > 2*time.Second {
		t.Errorf("parsing took %v", d)
	}
}

