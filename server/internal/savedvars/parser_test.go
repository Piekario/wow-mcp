// Code review 2026-11-16: a hostile SavedVariables file must not hang the parser or make it allocate more than its
// input warrants. Memory stays proportional to the input (the file size is capped by storage.MaxDumpBytes).
func TestParseHostileInputsAreBoundedAndFast(t *testing.T) {
	huge := strings.Repeat("x", 4<<20)
	cases := map[string]struct {
		src     string
		wantErr bool
	}{
		"sparse huge integer keys":  {"X = {[9223372036854775807] = 1, [1] = 2, [-9223372036854775808] = 3}", false},
		"float key too big for int": {"X = {[1e308] = 1}", false},
		"nesting through keys":      {"X = " + strings.Repeat("{[", maxDepth+1) + "1" + strings.Repeat("]=1}", maxDepth+1), true},
		"unterminated block":        {"--[[" + strings.Repeat("a", 1<<20), false},
		"unterminated string":       {`X = "` + huge, true},
		"long string":               {`X = "` + huge + `"`, false},
		"decimal escape over 255":   {`X = "\999"`, true},
		"lone minus":                {"X = -", true},
		"many empty tables":         {"X = {" + strings.Repeat("{},", 200000) + "}", false},
		"garbage":                   {"X = {\x00\xff}", true},
	}
	for name, c := range cases {
		start := time.Now()
		_, err := Parse([]byte(c.src))
		if (err != nil) != c.wantErr {
			t.Errorf("%s: error %v, want error %v", name, err, c.wantErr)
		}
		if d := time.Since(start); d > 2*time.Second {
			t.Errorf("%s: took %v", name, d)
		}
	}
	// A decimal escape up to 255 is one byte, as in Lua.
	vars, err := Parse([]byte(`X = "\255\0651"`))
	if err != nil || vars["X"] != "\xffA1" {
		t.Errorf("decimal escapes: %q %v", vars["X"], err)
	}
}
